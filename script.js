/* ========== LIVE PROCUREMENT STATUS (synced with Operator) ========== */
const PROC_STAGE_ORDER = ["weighed", "quality", "accepted", "payment_initiated", "payment_done"];
const PROC_STAGE_LABELS = {
  weighed: "Weighed",
  quality: "Quality Check",
  accepted: "Accepted",
  payment_initiated: "Payment Initiated",
  payment_done: "Payment Done"
};

function formatTimeShort(iso) {
  if (!iso) return "";
  try {
    const d = new Date(iso);
    return d.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" });
  } catch (e) {
    return "";
  }
}

function renderProcurementStatus(booking) {
  const timeline = document.getElementById("procTimeline");
  const details = document.getElementById("procDetails");
  const livePill = document.getElementById("procLivePill");
  const nextPill = document.getElementById("nextSlotPill");
  const nextToken = document.getElementById("nextSlotToken");
  const nextCentre = document.getElementById("nextSlotCentre");

  if (!booking) {
    if (timeline) {
      timeline.querySelectorAll("[data-stage]").forEach(function (el, idx) {
        el.className = "pending";
        el.innerHTML = (idx + 1) + "<span>" + (PROC_STAGE_LABELS[el.dataset.stage] || el.dataset.stage) + "</span>";
      });
    }
    if (details) details.innerHTML = '<div style="color:#94a3b8;">○ No active procurement. Book a slot to track live status.</div>';
    if (livePill) livePill.style.display = "none";
    return;
  }

  const stage = booking.procurementStage || null;
  const stageIdx = stage ? PROC_STAGE_ORDER.indexOf(stage) : -1;

  // Timeline circles
  if (timeline) {
    timeline.querySelectorAll("[data-stage]").forEach(function (el) {
      const s = el.dataset.stage;
      const i = PROC_STAGE_ORDER.indexOf(s);
      if (stageIdx >= 0 && i < stageIdx) {
        el.className = "done";
        el.innerHTML = "✓<span>" + (PROC_STAGE_LABELS[s] || s) + "</span>";
      } else if (stageIdx >= 0 && i === stageIdx) {
        el.className = "active";
        el.innerHTML = (i + 1) + "<span>" + (PROC_STAGE_LABELS[s] || s) + "</span>";
      } else {
        el.className = "pending";
        el.innerHTML = (i + 1) + "<span>" + (PROC_STAGE_LABELS[s] || s) + "</span>";
      }
    });
  }

  // Detail lines
  if (details) {
    let lines = [];
    if (booking.weighedAt || stageIdx >= 0) {
      const qty = booking.weighedQty ? " • " + booking.weighedQty + " " + (booking.weighedUnit || "Qtl") : "";
      const t = formatTimeShort(booking.weighedAt);
      lines.push(
        stageIdx > 0 || booking.weighedAt
          ? "✓ Weighed" + (t ? " — " + t : "") + qty
          : "○ Weighed — pending"
      );
    }
    if (booking.qualityAt || stageIdx >= 1) {
      const grade = booking.qualityGrade ? " • Grade " + booking.qualityGrade : "";
      const t = formatTimeShort(booking.qualityAt);
      lines.push(
        stageIdx > 1 || booking.qualityAt
          ? "✓ Quality Check" + (t ? " — " + t : "") + grade
          : (stageIdx === 1 ? "● Quality Check — in progress" : "○ Quality Check — pending")
      );
    }
    if (booking.acceptedAt || stageIdx >= 2) {
      const t = formatTimeShort(booking.acceptedAt);
      lines.push(
        stageIdx > 2 || booking.acceptedAt
          ? "✓ Accepted" + (t ? " — " + t : "")
          : (stageIdx === 2 ? "● Accepted — in progress" : "○ Accepted — pending")
      );
    }
    if (booking.paymentInitiatedAt || stageIdx >= 3) {
      const amt = booking.paymentAmount ? " • ₹" + Number(booking.paymentAmount).toLocaleString("en-IN") : "";
      const t = formatTimeShort(booking.paymentInitiatedAt);
      lines.push(
        stageIdx > 3 || booking.paymentInitiatedAt
          ? '<span style="color:#0b7d2a;font-weight:600;">● Payment Initiated' + (t ? " — " + t : "") + amt + "</span>"
          : (stageIdx === 3 ? '<span style="color:#0b7d2a;font-weight:600;">● Payment Initiated — in progress</span>' : "○ Payment Initiated — pending")
      );
    }
    if (booking.paymentDoneAt || stageIdx >= 4) {
      const t = formatTimeShort(booking.paymentDoneAt);
      lines.push(
        stageIdx >= 4 || booking.paymentDoneAt
          ? "✓ Payment Done" + (t ? " — " + t : "")
          : "○ Payment Done — Expected in 1–2 days"
      );
    }

    if (!lines.length) {
      lines.push('<div style="color:#94a3b8;">○ Token active. Waiting for operator to start (Weighing)…</div>');
    }
    details.innerHTML = lines.map(function (l) {
      return l.indexOf("<") === 0 ? l : "<div>" + l + "</div>";
    }).join("");
  }

  if (livePill) {
    livePill.style.display = stage ? "inline-flex" : "none";
    livePill.textContent = stage === "payment_done" ? "DONE" : "● LIVE";
  }

  // My Next Slot updates
  if (nextToken && (booking.shortToken || booking.token)) {
    nextToken.textContent = booking.shortToken || SK_DB.displayToken(booking.token) || "—";
  }
  if (nextCentre && booking.centreName) {
    nextCentre.textContent = booking.centreName;
  }
  if (nextPill) {
    if (booking.kycVerified || booking.kycStatus === "verified") {
      nextPill.textContent = "KYC DONE";
      nextPill.style.background = "#e8f8ec";
      nextPill.style.color = "#0a6b24";
    }
    if (stage === "payment_done") {
      nextPill.textContent = "COMPLETED";
    } else if (stage) {
      nextPill.textContent = "IN PROGRESS";
    }
  }
}

let _procUnsub = null;

function startLiveProcurementTracking() {
  const token = localStorage.getItem("kycToken") || localStorage.getItem("sk_kyc_token");
  if (!token) {
    // try from last booking
    try {
      const raw = localStorage.getItem("sk_last_booking");
      if (raw) {
        const b = JSON.parse(raw);
        if (b && b.token) {
          renderProcurementStatus(b);
          if (typeof SK_DB !== "undefined" && SK_DB.listenBooking) {
            if (_procUnsub) _procUnsub();
            _procUnsub = SK_DB.listenBooking(b.token, function (data) {
              renderProcurementStatus(data);
            });
          }
          return;
        }
      }
    } catch (e) {}
    renderProcurementStatus(null);
    return;
  }

  // Initial local render
  try {
    const raw = localStorage.getItem("sk_last_booking");
    if (raw) renderProcurementStatus(JSON.parse(raw));
  } catch (e) {}

  if (typeof SK_DB !== "undefined" && SK_DB.listenBooking) {
    if (_procUnsub) _procUnsub();
    _procUnsub = SK_DB.listenBooking(token, function (data) {
      renderProcurementStatus(data);
    });
  }
}

// Boot after DOM + Firebase ready
document.addEventListener("DOMContentLoaded", function () {
  setTimeout(startLiveProcurementTracking, 800);
});
if (document.readyState !== "loading") {
  setTimeout(startLiveProcurementTracking, 800);
}

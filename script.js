function dayName(dateStr) {
  const d = new Date(dateStr + "T12:00:00");
  return d.toLocaleDateString("en-IN", { weekday: "short" });
}

function buildFarmTip(current, daily) {
  const rainCodes = [51, 53, 55, 61, 63, 65, 80, 81, 82, 95, 96, 99];
  const rainProb = current.precipitation_probability ?? 0;
  const code = current.weather_code;
  let tip = "";

  // Check next 2 days for rain
  let rainDay = null;
  if (daily && daily.time) {
    for (let i = 1; i < Math.min(3, daily.time.length); i++) {
      if (rainCodes.includes(daily.weather_code[i]) || (daily.precipitation_probability_max && daily.precipitation_probability_max[i] > 40)) {
        rainDay = dayName(daily.time[i]);
        break;
      }
    }
  }

  if (rainCodes.includes(code) || rainProb > 50) {
    tip = "🌧️ Rain likely today — avoid spraying pesticides & fertilizers. Protect harvested crop.";
  } else if (rainDay) {
    tip = `💡 Tip: ${rainDay} light/moderate rain expected — avoid spraying pesticides. Plan irrigation accordingly.`;
  } else if (current.temperature_2m > 38) {
    tip = "🌡️ High temperature — irrigate early morning or evening. Protect workers from heat.";
  } else if (current.temperature_2m < 10) {
    tip = "❄️ Cool weather — good for wheat & mustard. Watch for frost in open fields.";
  } else {
    tip = "✅ Good weather for field work. Check soil moisture before irrigation.";
  }
  return tip;
}

async function loadLiveWeather(lat = 28.5355, lon = 77.3910, placeName = "Noida") {
  const url = `https://api.open-meteo.com/v1/forecast?latitude=${lat}&longitude=${lon}&current=temperature_2m,relative_humidity_2m,weather_code,wind_speed_10m,precipitation_probability&daily=weather_code,temperature_2m_max,temperature_2m_min,precipitation_probability_max&timezone=Asia%2FKolkata&forecast_days=5`;

  try {
    const res = await fetch(url);
    if (!res.ok) throw new Error("Weather API error");
    const data = await res.json();
    const cur = data.current;
    const daily = data.daily;
    const info = weatherCodeInfo(cur.weather_code);

    // Current
    const tempEl = document.getElementById("weatherTemp");
    const iconEl = document.getElementById("weatherIcon");
    const locEl = document.getElementById("weatherLoc");
    const humEl = document.getElementById("weatherHumidity");
    const windEl = document.getElementById("weatherWind");
    const rainEl = document.getElementById("weatherRain");
    const tipEl = document.getElementById("weatherTip");
    const updatedEl = document.getElementById("weatherUpdated");
    const forecastEl = document.getElementById("weatherForecast");
    const pill = document.getElementById("weatherStatusPill");

    if (tempEl) tempEl.textContent = Math.round(cur.temperature_2m) + "°C";
    if (iconEl) iconEl.textContent = info.icon;
    if (locEl) locEl.textContent = `${placeName} • ${info.text}`;
    if (humEl) humEl.textContent = `Humidity ${Math.round(cur.relative_humidity_2m)}%`;
    if (windEl) windEl.textContent = `Wind ${Math.round(cur.wind_speed_10m)} km/h`;
    if (rainEl) rainEl.textContent = `Rain ${cur.precipitation_probability ?? 0}%`;
    if (tipEl) tipEl.textContent = buildFarmTip(cur, daily);
    if (pill) {
      pill.textContent = "● LIVE";
      pill.classList.add("live-pill");
    }
    if (updatedEl) {
      const now = new Date();
      updatedEl.textContent = `Source: Open-Meteo • Updated ${now.toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit" })} • Auto-refresh 30 min`;
    }

    // 4-day forecast (skip today or start from today)
    if (forecastEl && daily && daily.time) {
      let html = "";
      for (let i = 0; i < 4 && i < daily.time.length; i++) {
        const dInfo = weatherCodeInfo(daily.weather_code[i]);
        const maxT = Math.round(daily.temperature_2m_max[i]);
        html += `<div style="background:#f6faf5;padding:8px;border-radius:10px;">
          <div>${dayName(daily.time[i])}</div>
          <div style="font-size:18px;">${dInfo.icon}</div>
          <div>${maxT}°</div>
        </div>`;
      }
      forecastEl.innerHTML = html;
    }

    // Update marquee weather span if present
    updateMarqueeWeather(Math.round(cur.temperature_2m), info.text, daily);

    console.log("[SmartKisan] Live weather loaded for", placeName);
  } catch (err) {
    console.warn("Live weather failed:", err);
    const tipEl = document.getElementById("weatherTip");
    if (tipEl) tipEl.textContent = "💡 Could not load live weather. Showing last known advisory.";
    const pill = document.getElementById("weatherStatusPill");
    if (pill) {
      pill.textContent = "OFFLINE";
      pill.classList.remove("live-pill");
    }
  }
}

function updateMarqueeWeather(temp, text, daily) {
  const tracks = document.querySelectorAll(".marquee-track");
  if (!tracks.length) return;

  let rainNote = "";
  if (daily && daily.time) {
    const rainCodes = [51, 53, 55, 61, 63, 65, 80, 81, 82];
    for (let i = 1; i < Math.min(3, daily.time.length); i++) {
      if (rainCodes.includes(daily.weather_code[i])) {
        rainNote = ` • ${dayName(daily.time[i])} rain expected — avoid spraying`;
        break;
      }
    }
  }
  const weatherText = `🌤️ Today ${temp}°C ${text}${rainNote}`;

  tracks.forEach((track) => {
    const spans = track.querySelectorAll("span");
    spans.forEach((sp) => {
      if (sp.textContent.includes("🌤️") || sp.textContent.toLowerCase().includes("today") && sp.textContent.includes("°C")) {
        sp.textContent = weatherText;
      }
    });
  });
}

function tryGeoWeather() {
  if (!navigator.geolocation) {
    loadLiveWeather();
    return;
  }
  navigator.geolocation.getCurrentPosition(
    (pos) => {
      const { latitude, longitude } = pos.coords;
      // Reverse geocode is optional; keep simple place name
      loadLiveWeather(latitude, longitude, "Your Location");
    },
    () => loadLiveWeather(), // fallback Noida
    { timeout: 8000, maximumAge: 600000 }
  );
}


function applyLanguage(language) {
  currentLanguage = locales[language] ? language : "en";
  localStorage.setItem("smartKisanLanguage", currentLanguage);
  document.documentElement.lang = currentLanguage;
  document
    .querySelectorAll("[data-i18n]")
    .forEach((el) => (el.innerHTML = t(el.dataset.i18n)));
  document
    .querySelectorAll("[data-i18n-placeholder]")
    .forEach((el) => (el.placeholder = t(el.dataset.i18nPlaceholder)));
  document
    .querySelectorAll("[data-i18n-aria]")
    .forEach((el) => el.setAttribute("aria-label", t(el.dataset.i18nAria)));
  updateCurrentDateTime();
}
function updateCurrentDateTime() {
  const now = new Date(),
    locale = locales[currentLanguage] || "en-US";
  document.getElementById("currentDay").textContent = now.getDate();
  document.getElementById("currentDate").textContent = now.toLocaleDateString(
    locale,
    { month: "short", year: "numeric" },
  );
  document.getElementById("currentTime").textContent = now.toLocaleTimeString(
    locale,
    { hour: "numeric", minute: "2-digit", second: "2-digit" },
  );
}
